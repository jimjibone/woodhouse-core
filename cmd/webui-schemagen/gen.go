// preamble is the fixed part of the output: the descriptor types.
const preamble = `import { Service_ServiceType } from '$lib/api/v2/clients/client_service_pb';

export interface FeatureDescriptor {
	name: string;
	desc: string;
}

export interface FieldDescriptor {
	id: string;
	type: string;
	required: boolean;
	features: readonly string[];
	desc: string;
	unit?: string;
	options?: readonly string[];
	min?: number | string;
	max?: number | string;
	step?: number | string;
	minItems?: number;
	maxItems?: number;
	item?: FieldDescriptor;
	fields?: readonly FieldDescriptor[];
}

export interface AttributeDescriptor extends FieldDescriptor {
	perms: 'ro' | 'rw';
}

export interface CommandDescriptor {
	id: string;
	desc: string;
	features: readonly string[];
	params: readonly FieldDescriptor[];
	result: readonly FieldDescriptor[];
}

export interface EventDescriptor {
	id: string;
	desc: string;
	features: readonly string[];
	fields: readonly FieldDescriptor[];
}

export interface ServiceDescriptor {
	name: string;
	type: Service_ServiceType;
	desc: string;
	open: boolean;
	features: readonly FeatureDescriptor[];
	attributes: readonly AttributeDescriptor[];
	commands: readonly CommandDescriptor[];
	events: readonly EventDescriptor[];
}
`

// generate renders the TypeScript file for a schema.
func generate(s *schema.Schema) ([]byte, error) {
	var b bytes.Buffer
	p := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }

	p("// Code generated by webui-schemagen from the woodhouse-api service schema (version %d). DO NOT EDIT.\n\n", s.Version)
	b.WriteString(preamble)
	p("\nexport const SCHEMA_VERSION = %d;\n", s.Version)
	p("export const SCHEMA_VERSION_HEADER = %s;\n", quote(schema.HeaderName))

	for _, srv := range s.Services {
		name := pascal(srv.Name)
		p("\n")
		p("export const %s = {\n", name)
		p("\tname: %s,\n", quote(srv.Name))
		p("\ttype: Service_ServiceType.%s,\n", srv.ProtoName())

		p("\tfeatures: {")
		var feats []kv
		for _, f := range srv.Features {
			feats = append(feats, kv{lowerCamel(f.Name), f.Name})
		}
		if err := writeMap(&b, "\t", feats); err != nil {
			return nil, fmt.Errorf("service %s features: %w", srv.Name, err)
		}

		p("\tattributes: {")
		var attrs []kv
		for _, a := range srv.Attributes {
			attrs = append(attrs, kv{lowerCamel(a.Name), a.Name})
		}
		if err := writeMap(&b, "\t", attrs); err != nil {
			return nil, fmt.Errorf("service %s attributes: %w", srv.Name, err)
		}

		p("\tcommands: {")
		var cmds []kv
		for _, c := range srv.Commands {
			cmds = append(cmds, kv{lowerCamel(c.Name), c.Name})
		}
		if err := writeMap(&b, "\t", cmds); err != nil {
			return nil, fmt.Errorf("service %s commands: %w", srv.Name, err)
		}

		p("\tevents: {")
		var evs []kv
		for _, e := range srv.Events {
			evs = append(evs, kv{lowerCamel(e.Name), e.Name})
		}
		if err := writeMap(&b, "\t", evs); err != nil {
			return nil, fmt.Errorf("service %s events: %w", srv.Name, err)
		}

		opts, err := serviceOptions(srv)
		if err != nil {
			return nil, fmt.Errorf("service %s: %w", srv.Name, err)
		}
		p("\toptions: {")
		if len(opts) == 0 {
			p("},\n")
		} else {
			p("\n")
			for _, o := range opts {
				p("\t\t%s: [%s] as const,\n", propKey(o.key), joinQuoted(o.options))
			}
			p("\t},\n")
		}
		p("} as const;\n")
		p("export type %sFeature = typeof %s.features[keyof typeof %s.features];\n", name, name, name)
		p("export type %sAttribute = typeof %s.attributes[keyof typeof %s.attributes];\n", name, name, name)
		p("export type %sCommand = typeof %s.commands[keyof typeof %s.commands];\n", name, name, name)
		p("export type %sEvent = typeof %s.events[keyof typeof %s.events];\n", name, name, name)
	}

	p("\nexport const SERVICES: readonly ServiceDescriptor[] = [\n")
	for _, srv := range s.Services {
		writeService(&b, srv)
	}
	p("];\n")

	p("\nconst servicesByType = new Map<Service_ServiceType, ServiceDescriptor>(SERVICES.map((srv) => [srv.type, srv]));\n")
	p("\nexport function serviceByType(t: Service_ServiceType): ServiceDescriptor | undefined {\n")
	p("\treturn servicesByType.get(t);\n")
	p("}\n")

	return b.Bytes(), nil
}

type kv struct{ key, value string }

// writeMap writes the body of an object literal whose opening brace is
// already written, through the closing "},".
func writeMap(b *bytes.Buffer, indent string, entries []kv) error {
	if len(entries) == 0 {
		b.WriteString("},\n")
		return nil
	}
	b.WriteString("\n")
	seen := map[string]string{}
	for _, e := range entries {
		if prev, dup := seen[e.key]; dup {
			return fmt.Errorf("%q and %q both map to %q", prev, e.value, e.key)
		}
		seen[e.key] = e.value
		fmt.Fprintf(b, "%s\t%s: %s,\n", indent, propKey(e.key), quote(e.value))
	}
	fmt.Fprintf(b, "%s},\n", indent)
	return nil
}

type optionSet struct {
	key     string
	options []string
}

// serviceOptions collects the fixed enum options of a service's fields. The
// key is the attribute id, "command.param", "command.result.field" or
// "event.field"; nested struct fields append ".field", and a list item uses
// its list's key.
func serviceOptions(srv *schema.Service) ([]optionSet, error) {
	var out []optionSet
	seen := map[string]bool{}
	var err error
	add := func(key string, f *schema.Field) {
		var walk func(key string, f *schema.Field)
		walk = func(key string, f *schema.Field) {
			if len(f.Options) > 0 {
				if seen[key] {
					err = fmt.Errorf("duplicate options key %q", key)
				}
				seen[key] = true
				out = append(out, optionSet{key, f.Options})
			}
			if f.Item != nil {
				walk(key, f.Item)
			}
			for _, sub := range f.Fields {
				walk(key+"."+sub.Name, sub)
			}
		}
		walk(key, f)
	}
	for _, a := range srv.Attributes {
		add(a.Name, a)
	}
	for _, c := range srv.Commands {
		for _, f := range c.Params {
			add(c.Name+"."+f.Name, f)
		}
		for _, f := range c.Result {
			add(c.Name+".result."+f.Name, f)
		}
	}
	for _, e := range srv.Events {
		for _, f := range e.Fields {
			add(e.Name+"."+f.Name, f)
		}
	}
	return out, err
}

func writeService(b *bytes.Buffer, srv *schema.Service) {
	p := func(format string, args ...any) { fmt.Fprintf(b, format, args...) }
	p("\t{\n")
	p("\t\tname: %s,\n", quote(srv.Name))
	p("\t\ttype: Service_ServiceType.%s,\n", srv.ProtoName())
	p("\t\tdesc: %s,\n", quote(srv.Desc))
	p("\t\topen: %t,\n", srv.Open)

	p("\t\tfeatures: [")
	if len(srv.Features) > 0 {
		p("\n")
		for _, f := range srv.Features {
			p("\t\t\t{ name: %s, desc: %s },\n", quote(f.Name), quote(f.Desc))
		}
		p("\t\t")
	}
	p("],\n")

	p("\t\tattributes: [")
	if len(srv.Attributes) > 0 {
		p("\n")
		for _, a := range srv.Attributes {
			writeField(b, "\t\t\t", a, string(a.Perms))
		}
		p("\t\t")
	}
	p("],\n")

	p("\t\tcommands: [")
	if len(srv.Commands) > 0 {
		p("\n")
		for _, c := range srv.Commands {
			p("\t\t\t{\n")
			p("\t\t\t\tid: %s,\n", quote(c.Name))
			p("\t\t\t\tdesc: %s,\n", quote(c.Desc))
			p("\t\t\t\tfeatures: [%s],\n", joinQuoted(c.Features))
			writeFields(b, "\t\t\t\t", "params", c.Params)
			writeFields(b, "\t\t\t\t", "result", c.Result)
			p("\t\t\t},\n")
		}
		p("\t\t")
	}
	p("],\n")

	p("\t\tevents: [")
	if len(srv.Events) > 0 {
		p("\n")
		for _, e := range srv.Events {
			p("\t\t\t{\n")
			p("\t\t\t\tid: %s,\n", quote(e.Name))
			p("\t\t\t\tdesc: %s,\n", quote(e.Desc))
			p("\t\t\t\tfeatures: [%s],\n", joinQuoted(e.Features))
			writeFields(b, "\t\t\t\t", "fields", e.Fields)
			p("\t\t\t},\n")
		}
		p("\t\t")
	}
	p("],\n")
	p("\t},\n")
}

// writeFields writes "key: [ ... ],".
func writeFields(b *bytes.Buffer, indent, key string, fields []*schema.Field) {
	fmt.Fprintf(b, "%s%s: [", indent, key)
	if len(fields) > 0 {
		b.WriteString("\n")
		for _, f := range fields {
			writeField(b, indent+"\t", f, "")
		}
		b.WriteString(indent)
	}
	b.WriteString("],\n")
}

// writeField writes one field object, "{ ... },". perms is set for attributes.
func writeField(b *bytes.Buffer, indent string, f *schema.Field, perms string) {
	p := func(format string, args ...any) { fmt.Fprintf(b, format, args...) }
	p("%s{\n", indent)
	in := indent + "\t"
	p("%sid: %s,\n", in, quote(f.Name))
	p("%stype: %s,\n", in, quote(string(f.Type)))
	if perms != "" {
		p("%sperms: %s,\n", in, quote(perms))
	}
	p("%srequired: %t,\n", in, f.Required)
	p("%sfeatures: [%s],\n", in, joinQuoted(f.Features))
	p("%sdesc: %s,\n", in, quote(f.Desc))
	if f.Unit != "" {
		p("%sunit: %s,\n", in, quote(f.Unit))
	}
	if len(f.Options) > 0 {
		p("%soptions: [%s],\n", in, joinQuoted(f.Options))
	}
	switch f.Type {
	case schema.TypeInt, schema.TypeFloat:
		writeNum(b, in, "min", f.Min)
		writeNum(b, in, "max", f.Max)
		writeNum(b, in, "step", f.Step)
	case schema.TypeDuration:
		// Durations stay as written in the schema ("300s").
		writeRaw(b, in, "min", f.RawMin)
		writeRaw(b, in, "max", f.RawMax)
		writeRaw(b, in, "step", f.RawStep)
	}
	if f.MinItems != nil {
		p("%sminItems: %d,\n", in, *f.MinItems)
	}
	if f.MaxItems != nil {
		p("%smaxItems: %d,\n", in, *f.MaxItems)
	}
	if f.Item != nil {
		var tmp bytes.Buffer
		writeField(&tmp, in, f.Item, "")
		p("%sitem: %s", in, strings.TrimLeft(tmp.String(), "\t"))
	}
	if len(f.Fields) > 0 {
		writeFields(b, in, "fields", f.Fields)
	}
	p("%s},\n", indent)
}

func writeNum(b *bytes.Buffer, indent, key string, v *float64) {
	if v != nil {
		fmt.Fprintf(b, "%s%s: %s,\n", indent, key, strconv.FormatFloat(*v, 'g', -1, 64))
	}
}

func writeRaw(b *bytes.Buffer, indent, key string, v any) {
	if s, ok := v.(string); ok {
		fmt.Fprintf(b, "%s%s: %s,\n", indent, key, quote(s))
	}
}

// pascal converts snake_case to PascalCase, e.g. "on_off" -> "OnOff".
func pascal(s string) string {
	var b strings.Builder
	for _, part := range strings.Split(s, "_") {
		if part == "" {
			continue
		}
		b.WriteString(strings.ToUpper(part[:1]) + part[1:])
	}
	return b.String()
}

// lowerCamel converts snake_case to camelCase, e.g. "set_schedule" ->
// "setSchedule".
func lowerCamel(s string) string {
	p := pascal(s)
	if p == "" {
		return p
	}
	return strings.ToLower(p[:1]) + p[1:]
}

// propKey returns a key usable in an object literal, quoted when it is not a
// plain identifier.
func propKey(k string) string {
	for i, r := range k {
		ok := r == '_' || r == '$' || (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || (i > 0 && r >= '0' && r <= '9')
		if !ok {
			return quote(k)
		}
	}
	return k
}

func joinQuoted(ss []string) string {
	q := make([]string, len(ss))
	for i, s := range ss {
		q[i] = quote(s)
	}
	return strings.Join(q, ", ")
}

// quote returns a single-quoted TypeScript string literal, ASCII only.
func quote(s string) string {
	var b strings.Builder
	b.WriteByte('\'')
	for _, r := range s {
		switch {
		case r == '\\':
			b.WriteString(`\\`)
		case r == '\'':
			b.WriteString(`\'`)
		case r == '\n':
			b.WriteString(`\n`)
		case r == '\r':
			b.WriteString(`\r`)
		case r == '\t':
			b.WriteString(`\t`)
		case r < 0x20 || r >= 0x7f:
			if r > 0xffff {
				fmt.Fprintf(&b, `\u{%x}`, r)
			} else {
				fmt.Fprintf(&b, `\u%04x`, r)
			}
		default:
			b.WriteRune(r)
		}
	}
	b.WriteByte('\'')
	return b.String()
}
